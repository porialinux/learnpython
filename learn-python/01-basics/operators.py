# Python Operators

# Arithmetic operators
a = 10
b = 3

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor division:", a // b)
print("Remainder:", a % b)
print("Power:", a ** b)


# Comparison operators
x = 10
y = 5

print(x > y)   # Greater than
print(x < y)   # Less than
print(x == y)  # Equal
print(x != y)  # Not equal


# Logical operators
is_python = True
is_fun = True

print(is_python and is_fun)
print(is_python or False)
print(not False)
